//! `wwm progress [--write|--check]` — port of `tools/progress.py`.
//!
//! Difference from Python (by design, same numbers): when a dump (`strings.jsonl`,
//! `strings_diff.jsonl`) is missing, the tracked binary is decoded in memory instead
//! of failing, so CI needs no dump step on the Rust path.

use crate::Code;
use crate::dict::{UniqueRec, load_translated_map};
use crate::dump;
use crate::profiles::Profile;
use crate::py::{basename, for_each_jsonl, glob, num, pct, repr_list};
use anyhow::{Context, Result};
use serde::Deserialize;
use std::collections::{HashMap, HashSet};

pub const START: &str =
    "<!-- progress:start — generated by tools/progress.py, do not edit by hand -->";
pub const END: &str = "<!-- progress:end -->";

/// (label, lo, hi, total, done)
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Row {
    pub label: String,
    pub lo: i64,
    pub hi: i64,
    pub total: i64,
    pub done: i64,
}

#[derive(Deserialize)]
struct IdxOnly {
    idx: i64,
}

pub fn phase_rows(p: &Profile) -> Result<Vec<Row>> {
    let known: HashSet<&str> = p.phases.iter().map(|ph| ph.1.as_str()).collect();
    let extra: Vec<String> = glob(&p.locale_dir.join("*.jsonl").to_string_lossy())?
        .iter()
        .map(|f| basename(f))
        .filter(|b| !known.contains(b.as_str()))
        .collect();
    if !extra.is_empty() {
        crate::exit!(
            "file locale tanpa entri di phases (tambahkan ke tools/profiles.json): {}",
            repr_list(&extra)
        );
    }
    let mut rows = Vec::new();
    for ph in &p.phases {
        let (label, fname, lo, hi) = (&ph.0, &ph.1, ph.2, ph.3);
        let path = p.locale_dir.join(fname);
        let mut done = 0i64;
        let mut last: Option<i64> = None;
        if path.exists() {
            let mut err = None;
            for_each_jsonl(&path, |_, r: IdxOnly| {
                let i = r.idx;
                let want = last.map_or(lo, |l| l + 1);
                if err.is_none() && (i != want || i > hi) {
                    err = Some(format!(
                        "{fname}: idx {i} tidak berurutan dari {lo} atau di luar {lo}–{hi} (jalankan tools/qa_check.py --locale)"
                    ));
                }
                last = Some(i);
                done += 1;
                Ok(())
            })?;
            if let Some(e) = err {
                crate::exit!("{e}");
            }
        }
        rows.push(Row {
            label: label.clone(),
            lo,
            hi,
            total: hi - lo + 1,
            done,
        });
    }
    Ok(rows)
}

fn freq_coverage(p: &Profile, tr: &HashMap<String, String>) -> Result<(u64, u64)> {
    let (mut total, mut hit) = (0u64, 0u64);
    for_each_jsonl(&p.unique, |_, d: UniqueRec| {
        let f = d.freq.context("unique_strings.jsonl tanpa kolom freq")?;
        total += f;
        if tr.contains_key(&d.v) {
            hit += f;
        }
        Ok(())
    })?;
    Ok((hit, total))
}

fn dump_coverage(
    p: &Profile,
    name: &str,
    d: &str,
    tr: &HashMap<String, String>,
) -> Result<(u64, u64)> {
    let hint = format!("{d} tidak ada — jalankan dulu: python wwm_locmap.py dump {name} {d}");
    let (mut total, mut hit) = (0u64, 0u64);
    for r in dump::load(p, name, d, &hint)? {
        if let Some(v) = r.v {
            total += 1;
            hit += tr.contains_key(&v) as u64;
        }
    }
    Ok((hit, total))
}

fn sum<F: Fn(&Row) -> i64>(rows: &[&Row], f: F) -> u64 {
    rows.iter().map(|r| f(r)).sum::<i64>() as u64
}

pub fn build_block(p: &Profile) -> Result<String> {
    let rows = phase_rows(p)?;
    let (tr, _) = load_translated_map(p)?;
    let all: Vec<&Row> = rows.iter().collect();
    let orig: Vec<&Row> = rows
        .iter()
        .filter(|r| !r.label.starts_with("Update"))
        .collect();
    let upd: Vec<&Row> = rows
        .iter()
        .filter(|r| r.label.starts_with("Update"))
        .collect();
    let (all_total, all_done) = (sum(&all, |r| r.total), sum(&all, |r| r.done));
    let (o_total, o_done) = (sum(&orig, |r| r.total), sum(&orig, |r| r.done));
    let (u_total, u_done) = (sum(&upd, |r| r.total), sum(&upd, |r| r.done));

    let mut out: Vec<String> = vec![
        START.into(),
        "".into(),
        "## Overall progress".into(),
        "".into(),
        "| Measure | Done | Total | % |".into(),
        "| --- | ---: | ---: | ---: |".into(),
        format!(
            "| **Unique strings translated (all)** | **{}** | **{}** | **{}** |",
            num(all_done),
            num(all_total),
            pct(all_done, all_total)
        ),
        format!(
            "| ↳ {} | {} | {} | {} |",
            p.corpus_label,
            num(o_done),
            num(o_total),
            pct(o_done, o_total)
        ),
    ];
    if !upd.is_empty() {
        out.push(format!(
            "| ↳ game-update strings (Update-N) | {} | {} | {} |",
            num(u_done),
            num(u_total),
            pct(u_done, u_total)
        ));
    }
    if p.coverage == "freq" {
        let (h, t) = freq_coverage(p, &tr)?;
        out.push(format!(
            "| **In-game text coverage** — CN-only `{}` entries (`freq` in `unique_strings.jsonl`; keys shared with global come via the bridge) | **{}** | **{}** | **{}** |",
            p.dumps[0].0,
            num(h),
            num(t),
            pct(h, t)
        ));
    }
    if p.coverage == "dump" {
        for (name, d) in &p.dumps {
            let (h, t) = dump_coverage(p, name, d, &tr)?;
            out.push(format!(
                "| **In-game text coverage** — `{name}` entries (`{d}`) | **{}** | **{}** | **{}** |",
                num(h),
                num(t),
                pct(h, t)
            ));
        }
    }
    out.push("".into());
    out.push(format!(
        "Unique strings = rows of `unique_strings.jsonl` with a translation in `{}/`. In-game coverage counts every entry of the dumped file whose text has a translation — higher than the unique share because the earliest phases hold the most frequent strings.",
        p.locale_rel()
    ));
    out.push("".into());
    out.push("## Phase status".into());
    out.push("".into());
    out.extend(status_table(p, &rows));
    out.push("".into());
    out.push(END.into());
    Ok(out.join("\n"))
}

fn line(name: &str, part: &[&Row]) -> String {
    let (lo, hi) = (part[0].lo, part[part.len() - 1].hi);
    let total: i64 = part.iter().map(|r| r.total).sum();
    let done: i64 = part.iter().map(|r| r.done).sum();
    let status = if done == total {
        "done"
    } else if done > 0 {
        "**active**"
    } else {
        "not started"
    };
    let nxt = part
        .iter()
        .find(|r| r.done < r.total)
        .map(|r| num(r.lo + r.done))
        .unwrap_or_else(|| "—".into());
    format!(
        "| {} | {}–{} | {} | {} | {} / {} | {} |",
        name,
        num(lo),
        num(hi),
        status,
        nxt,
        num(done),
        num(total),
        pct(done as u64, total as u64)
    )
}

/// Phase status table: per game region when the profile has `regions`, else per phase.
pub fn status_table(p: &Profile, rows: &[Row]) -> Vec<String> {
    let by_label: HashMap<&str, &Row> = rows.iter().map(|r| (r.label.as_str(), r)).collect();
    let mut used: HashSet<&str> = HashSet::new();
    type Group<'a> = (&'a str, &'a str, Vec<(&'a Row, &'a str)>);
    let mut groups: Vec<Group> = Vec::new();
    for reg in &p.regions {
        let members: Vec<(&Row, &str)> = reg
            .2
            .iter()
            .filter_map(|(l, part)| by_label.get(l.as_str()).map(|r| (*r, part.as_str())))
            .collect();
        for (r, _) in &members {
            used.insert(r.label.as_str());
        }
        if !members.is_empty() {
            groups.push((&reg.0, &reg.1, members));
        }
    }
    let mut out = vec![
        format!(
            "| {} | Range | Status | Next idx | Done / total | % |",
            if groups.is_empty() { "Phase" } else { "Region" }
        ),
        "| --- | --- | --- | --- | ---: | ---: |".to_string(),
    ];
    for (name, tag, members) in &groups {
        let part_rows: Vec<&Row> = members.iter().map(|(r, _)| *r).collect();
        out.push(line(&format!("**{name}** ({tag})"), &part_rows));
        if part_rows.iter().any(|r| r.done < r.total) && members.len() > 1 {
            for (r, part) in members {
                out.push(line(&format!("↳ {name} {part} (`{}`)", r.label), &[r]));
            }
        }
    }
    for r in rows.iter().filter(|r| !used.contains(r.label.as_str())) {
        out.push(line(&r.label, &[r]));
    }
    out
}

/// (document, START position, END position) of the profile's status file.
pub fn read_status(p: &Profile) -> Result<(String, usize, usize)> {
    let doc =
        std::fs::read_to_string(&p.status).with_context(|| format!("{}", p.status.display()))?;
    match (doc.find(START), doc.find(END)) {
        (Some(s), Some(e)) if e >= s => Ok((doc, s, e)),
        _ => crate::exit!("penanda progress tidak ditemukan di {}", p.status.display()),
    }
}

/// True when the profile's status block does not match the current data.
pub fn is_stale(p: &Profile) -> Result<bool> {
    let block = build_block(p)?;
    let (doc, s, e) = read_status(p)?;
    Ok(doc[s..e + END.len()].replace("\r\n", "\n") != block)
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Mode {
    Print,
    Write,
    Check,
}

pub fn run(p: &Profile, mode: Mode) -> Result<Code> {
    let block = build_block(p)?;
    let (doc, s, e) = read_status(p)?;
    let nl = if doc.contains("\r\n") { "\r\n" } else { "\n" };
    let current = doc[s..e + END.len()].replace("\r\n", "\n");
    let flag = if p.name == "global" {
        String::new()
    } else {
        format!(" --profile {}", p.name)
    };
    match mode {
        Mode::Check => {
            if current != block {
                println!(
                    "{}: blok progress basi — jalankan `python tools/progress.py{} --write` dan commit hasilnya.",
                    p.status_rel, flag
                );
                return Ok(1);
            }
            println!("{}: blok progress sesuai data.", p.status_rel);
        }
        Mode::Write => {
            let new = format!(
                "{}{}{}",
                &doc[..s],
                block.replace('\n', nl),
                &doc[e + END.len()..]
            );
            std::fs::write(&p.status, new).with_context(|| format!("{}", p.status.display()))?;
            println!("ditulis: {}", p.status.display());
        }
        Mode::Print => println!("{block}"),
    }
    Ok(0)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::profiles::{get, testutil};

    fn row(label: &str, lo: i64, hi: i64, done: i64) -> Row {
        Row {
            label: label.into(),
            lo,
            hi,
            total: hi - lo + 1,
            done,
        }
    }

    #[test]
    fn status_table_groups_regions() {
        let d = testutil::repo();
        let p = get(d.path(), "global").unwrap();
        let rows = vec![
            row("0", 0, 2, 3),
            row("1", 3, 5, 3),
            row("Update-1A", 6, 7, 1),
            row("Update-1B", 8, 9, 0),
        ];
        assert_eq!(
            status_table(&p, &rows),
            [
                "| Region | Range | Status | Next idx | Done / total | % |",
                "| --- | --- | --- | --- | ---: | ---: |",
                "| **Start** (Phase 0–1) | 0–5 | done | — | 6 / 6 | 100.00% |",
                "| **Next** (Update-1) | 6–9 | **active** | 7 | 1 / 4 | 25.00% |",
                "| ↳ Next Part A (`Update-1A`) | 6–7 | **active** | 7 | 1 / 2 | 50.00% |",
                "| ↳ Next Part B (`Update-1B`) | 8–9 | not started | 8 | 0 / 2 | 0.00% |",
            ]
        );
        let c = get(d.path(), "cn").unwrap();
        assert_eq!(
            status_table(&c, &[row("1", 0, 30000, 1234)]),
            [
                "| Phase | Range | Status | Next idx | Done / total | % |",
                "| --- | --- | --- | --- | ---: | ---: |",
                "| 1 | 0–30,000 | **active** | 1,234 | 1,234 / 30,001 | 4.11% |",
            ]
        );
    }

    fn setup() -> tempfile::TempDir {
        let d = testutil::repo();
        crate::dict::tests_seed(d.path());
        testutil::write(
            d.path(),
            "strings.jsonl",
            "{\"b\": 1, \"s\": 0, \"h\": \"01\", \"v\": \"Hello\"}\n{\"b\": 1, \"s\": 1, \"h\": \"02\", \"v\": \"Hello\"}\n{\"b\": 1, \"s\": 2, \"h\": \"03\", \"v\": \"Nope\"}\n",
        );
        testutil::write(
            d.path(),
            "strings_diff.jsonl",
            "{\"b\": 1, \"s\": 0, \"h\": \"04\", \"deleted\": true}\n",
        );
        testutil::write(
            d.path(),
            "Obsidian-Vault/progress/Current-Status.md",
            &format!("# Status\r\n\r\n{START}\r\nold\r\n{END}\r\n\r\ntail\r\n"),
        );
        d
    }

    #[test]
    fn block_write_and_check() {
        let d = setup();
        let p = get(d.path(), "global").unwrap();
        let block = build_block(&p).unwrap();
        assert!(
            block.contains("| **Unique strings translated (all)** | **3** | **10** | **30.00%** |"),
            "{block}"
        );
        assert!(
            block.contains("| ↳ original corpus (Phases 0–1) | 3 | 6 | 50.00% |"),
            "{block}"
        );
        assert!(
            block.contains("| ↳ game-update strings (Update-N) | 0 | 4 | 0.00% |"),
            "{block}"
        );
        assert!(block.contains("| **In-game text coverage** — `translate_words_map_en` entries (`strings.jsonl`) | **2** | **3** | **66.67%** |"));
        assert!(block.contains("| **In-game text coverage** — `translate_words_map_en_diff` entries (`strings_diff.jsonl`) | **0** | **0** | **—** |"));
        assert!(is_stale(&p).unwrap());
        assert_eq!(run(&p, Mode::Check).unwrap(), 1);
        assert_eq!(run(&p, Mode::Write).unwrap(), 0);
        assert!(!is_stale(&p).unwrap());
        assert_eq!(run(&p, Mode::Check).unwrap(), 0);
        let doc = std::fs::read_to_string(&p.status).unwrap();
        assert!(doc.starts_with("# Status\r\n\r\n<!-- progress:start"));
        assert!(doc.ends_with("<!-- progress:end -->\r\n\r\ntail\r\n"));
        assert!(
            !doc.replace("\r\n", "").contains('\n'),
            "LF-only lines in a CRLF doc"
        );
    }

    #[test]
    fn unknown_locale_file_and_gap_exit() {
        let d = setup();
        let p = get(d.path(), "global").unwrap();
        testutil::write(
            d.path(),
            "locale/phase9.jsonl",
            "{\"idx\": 0, \"v\": \"x\"}\n",
        );
        let e = phase_rows(&p).unwrap_err();
        assert_eq!(
            e.to_string(),
            "file locale tanpa entri di phases (tambahkan ke tools/profiles.json): ['phase9.jsonl']"
        );
        std::fs::remove_file(d.path().join("locale").join("phase9.jsonl")).unwrap();
        testutil::write(
            d.path(),
            "locale/phase1.jsonl",
            "{\"idx\": 4, \"v\": \"x\"}\n",
        );
        let e = phase_rows(&p).unwrap_err();
        assert_eq!(
            e.to_string(),
            "phase1.jsonl: idx 4 tidak berurutan dari 3 atau di luar 3–5 (jalankan tools/qa_check.py --locale)"
        );
    }
}
