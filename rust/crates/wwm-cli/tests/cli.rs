//! End-to-end tests of the `wwm` binary on a throw-away repo (WWM_ROOT).

use assert_cmd::Command;
use std::path::Path;
use wwm_locmap::{
    Header, TOMBSTONE, build_index, build_shard, parse_shard, read_container_ex, write_container_ex,
};

const PROFILES: &str = r#"{
  "global": {
    "base": ".",
    "phases": [["0", "phase0.jsonl", 0, 2], ["Update-1", "update1.jsonl", 3, 4]],
    "regions": [],
    "files": ["translate_words_map_en", "translate_words_map_en_diff"],
    "dumps": [["translate_words_map_en", "strings.jsonl"], ["translate_words_map_en_diff", "strings_diff.jsonl"]],
    "status": "Current-Status.md",
    "coverage": "dump",
    "corpus_label": "original corpus (Phase 0)",
    "patched_dir": "patched",
    "translated_out": "strings.translated.jsonl",
    "bridge_from": null,
    "overrides": null
  }
}"#;

fn write(root: &Path, rel: &str, text: &str) {
    let p = root.join(rel);
    std::fs::create_dir_all(p.parent().unwrap()).unwrap();
    std::fs::write(p, text).unwrap();
}

fn repo() -> tempfile::TempDir {
    let d = tempfile::tempdir().unwrap();
    let r = d.path();
    write(r, "tools/profiles.json", PROFILES);
    write(
        r,
        "translation_work/unique_strings.jsonl",
        "{\"idx\": 0, \"freq\": 3, \"v\": \"Hello\"}\n{\"idx\": 1, \"freq\": 1, \"v\": \"#YWorld#E\"}\n{\"idx\": 2, \"freq\": 1, \"v\": \"Bye\"}\n{\"idx\": 3, \"freq\": 1, \"v\": \"New\"}\n{\"idx\": 4, \"freq\": 1, \"v\": \"Newer\"}\n",
    );
    write(
        r,
        "locale/phase0.jsonl",
        "{\"idx\": 0, \"v\": \"Halo\"}\n{\"idx\": 1, \"v\": \"#YDunia#E\"}\n",
    );
    write(r, "locale/update1.jsonl", "{\"idx\": 3, \"v\": \"Baru\"}\n");
    write(
        r,
        "Current-Status.md",
        "# S\n\n<!-- progress:start — generated by tools/progress.py, do not edit by hand -->\n<!-- progress:end -->\n",
    );
    let base = vec![
        build_index(4, 2),
        build_shard(16, 1, &[(2, 0x11, b"Hello"), (7, 0x22, b"#YWorld#E")]),
        build_shard(8, 2, &[(1, 0x33, b"Hello"), (5, 0x44, b"Bye")]),
    ];
    write_container_ex(&r.join("translate_words_map_en"), &Header::v1(), &base, 3).unwrap();
    let diff = vec![
        build_index(9, 1),
        build_shard(8, 3, &[(0, 0x55, b"New"), (3, 0x66, TOMBSTONE)]),
    ];
    write_container_ex(
        &r.join("translate_words_map_en_diff"),
        &Header::v1(),
        &diff,
        3,
    )
    .unwrap();
    d
}

fn wwm(root: &Path) -> Command {
    let mut c = Command::cargo_bin("wwm").unwrap();
    c.current_dir(root)
        .env("WWM_ROOT", root)
        .env_remove("GITHUB_SHA");
    c
}

fn values(path: &Path, root: &Path) -> Vec<Vec<Vec<u8>>> {
    let (_, blocks) = read_container_ex(path, root).unwrap();
    blocks[1..]
        .iter()
        .map(|b| {
            parse_shard(b)
                .unwrap()
                .2
                .iter()
                .map(|e| e.value.to_vec())
                .collect()
        })
        .collect()
}

#[test]
fn info_dump_patch_round_trip() {
    let d = repo();
    let r = d.path();
    let out = wwm(r)
        .args(["info", "translate_words_map_en_diff"])
        .output()
        .unwrap();
    let s = String::from_utf8(out.stdout).unwrap();
    assert!(
        s.contains("entries parsed : 2")
            && s.contains("deleted (tombstone 0xFF): 1")
            && s.contains("note: parsed count"),
        "{s}"
    );

    wwm(r)
        .args(["dump", "translate_words_map_en", "strings.jsonl"])
        .assert()
        .success();
    let dump = std::fs::read_to_string(r.join("strings.jsonl"))
        .unwrap()
        .replace("\r\n", "\n");
    assert_eq!(
        dump,
        "{\"b\": 1, \"s\": 2, \"h\": \"0000000000000011\", \"v\": \"Hello\"}\n\
         {\"b\": 1, \"s\": 7, \"h\": \"0000000000000022\", \"v\": \"#YWorld#E\"}\n\
         {\"b\": 2, \"s\": 1, \"h\": \"0000000000000033\", \"v\": \"Hello\"}\n\
         {\"b\": 2, \"s\": 5, \"h\": \"0000000000000044\", \"v\": \"Bye\"}\n"
    );
    write(
        r,
        "edits.jsonl",
        "{\"b\": 2, \"s\": 5, \"h\": \"0000000000000044\", \"v\": \"Dah\"}\n",
    );
    wwm(r)
        .args([
            "patch",
            "translate_words_map_en",
            "edits.jsonl",
            "out.bin",
            "--level",
            "3",
        ])
        .assert()
        .success();
    assert_eq!(
        values(&r.join("out.bin"), r)[1],
        vec![b"Hello".to_vec(), b"Dah".to_vec()]
    );
    // wrong keyHash -> refused
    write(
        r,
        "bad.jsonl",
        "{\"b\": 2, \"s\": 5, \"h\": \"00000000000000ff\", \"v\": \"Dah\"}\n",
    );
    let o = wwm(r)
        .args(["patch", "translate_words_map_en", "bad.jsonl", "x.bin"])
        .output()
        .unwrap();
    assert_eq!(o.status.code(), Some(1));
    assert!(
        String::from_utf8_lossy(&o.stderr).contains("keyHash 00000000000000ff != 0000000000000044")
    );
    // empty slot / out of range block
    write(r, "bad.jsonl", "{\"b\": 2, \"s\": 0, \"v\": \"x\"}\n");
    assert_eq!(
        wwm(r)
            .args(["patch", "translate_words_map_en", "bad.jsonl", "x.bin"])
            .output()
            .unwrap()
            .status
            .code(),
        Some(1)
    );
    write(r, "bad.jsonl", "{\"b\": 9, \"s\": 0, \"v\": \"x\"}\n");
    let o = wwm(r)
        .args(["patch", "translate_words_map_en", "bad.jsonl", "x.bin"])
        .output()
        .unwrap();
    assert!(String::from_utf8_lossy(&o.stderr).contains("block di luar jangkauan 1..2: [9]"));
}

#[test]
fn qa_progress_patch_all_manifest() {
    let d = repo();
    let r = d.path();
    wwm(r)
        .args(["qa", "--locale", "locale/*.jsonl"])
        .assert()
        .success();
    // progress works without dumps (binaries decoded in memory)
    wwm(r).args(["progress", "--check"]).assert().code(1);
    wwm(r).args(["progress", "--write"]).assert().success();
    wwm(r).args(["progress", "--check"]).assert().success();
    let doc = std::fs::read_to_string(r.join("Current-Status.md")).unwrap();
    assert!(
        doc.contains("| **Unique strings translated (all)** | **3** | **5** | **60.00%** |"),
        "{doc}"
    );
    assert!(
        doc.contains(
            "`translate_words_map_en` entries (`strings.jsonl`) | **3** | **4** | **75.00%** |"
        ),
        "{doc}"
    );
    assert!(doc.contains("`translate_words_map_en_diff` entries (`strings_diff.jsonl`) | **1** | **1** | **100.00%** |"), "{doc}");

    // a translation that drops a token fails QA
    write(
        r,
        "locale/phase0.jsonl",
        "{\"idx\": 0, \"v\": \"Halo\"}\n{\"idx\": 1, \"v\": \"Dunia\"}\n",
    );
    wwm(r)
        .args(["qa", "--locale", "locale/*.jsonl"])
        .assert()
        .code(1);
    write(
        r,
        "locale/phase0.jsonl",
        "{\"idx\": 0, \"v\": \"Halo\"}\n{\"idx\": 1, \"v\": \"#YDunia#E\"}\n",
    );

    wwm(r)
        .args(["patch-all", "--level", "3"])
        .assert()
        .success();
    assert_eq!(
        values(&r.join("patched").join("translate_words_map_en"), r),
        vec![
            vec![b"Halo".to_vec(), b"#YDunia#E".to_vec()],
            vec![b"Halo".to_vec(), b"Bye".to_vec()]
        ]
    );
    assert_eq!(
        values(&r.join("patched").join("translate_words_map_en_diff"), r),
        vec![vec![b"Baru".to_vec(), TOMBSTONE.to_vec()]]
    );

    wwm(r)
        .args([
            "manifest",
            "--outdir",
            "patched",
            "--archive",
            "patch.zip",
            "--commit",
            "abc",
        ])
        .assert()
        .success();
    let m = std::fs::read_to_string(r.join("patched").join("manifest.json")).unwrap();
    assert!(
        m.contains("\"schema\": 2")
            && m.contains("\"commit\": \"abc\"")
            && m.contains("\"name\": \"patch.zip\""),
        "{m}"
    );
    assert!(r.join("patch.zip").exists());

    // rebuild-unique: nothing new ("Newer" exists, every live text is known)
    let o = wwm(r)
        .args(["rebuild-unique", "--dry-run"])
        .output()
        .unwrap();
    assert!(String::from_utf8_lossy(&o.stdout).contains("string baru (belum pernah tercatat): 0"));
    // build-unique refuses
    wwm(r).arg("build-unique").assert().code(1);
}
