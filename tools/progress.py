#!/usr/bin/env python3
"""
progress.py — hitung progress terjemahan secara otomatis dan tulis ke
Obsidian-Vault/progress/Current-Status.md (blok di antara penanda
`<!-- progress:start -->` dan `<!-- progress:end -->`).

    python tools/progress.py            # cetak saja
    python tools/progress.py --write    # perbarui blok di Current-Status.md
    python tools/progress.py --check    # exit 1 kalau blok tidak sesuai data (CI)
    python tools/progress.py --profile cn --write   # WWM China -> Obsidian-Vault/cn/progress/CN-Current-Status.md

Angka dihitung dari file yang ter-track di git (unique_strings.jsonl,
locale/*.jsonl) plus strings.jsonl dan strings_diff.jsonl, yang TIDAK ter-track
(strings.jsonl >100 MB sejak game v2.3) tapi deterministik: selalu hasil
`wwm_locmap.py dump` dari binary translate_words_map_en / _diff yang ter-track.
Jadi hasilnya sama di mesin mana pun dan --check bisa dipakai di CI (CI
men-dump keduanya dulu).

Profil cn menghitung coverage dari kolom `freq` cn/translation_work/unique_strings.jsonl
(jumlah kemunculan tiap teks di translate_words_map_zh_cn), bukan dari dump — dump CN
butuh keystream kamus yang tidak di-commit, jadi CI tidak bisa membuatnya.

Fase baru (Update-N setelah update game) harus ditambahkan ke tools/profiles.py.
"""
import argparse, glob, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from expand_locale import load_translated_map
import profiles

START = "<!-- progress:start — generated by tools/progress.py, do not edit by hand -->"
END = "<!-- progress:end -->"

# Fase per profil (termasuk Update-N global) ada di tools/profiles.py.
PHASES = profiles.GLOBAL.phases


def pct(a, b):
    return "%.2f%%" % (100.0 * a / b) if b else "—"


def num(n):
    return "{:,}".format(n)


def phase_rows(P):
    known = {f for _, f, _, _ in P.phases}
    extra = [os.path.basename(p) for p in glob.glob(os.path.join(P.locale_dir, "*.jsonl"))
             if os.path.basename(p) not in known]
    if extra:
        sys.exit("file locale tanpa entri di phases (tambahkan ke tools/profiles.py): %s" % extra)
    rows = []
    for label, fname, lo, hi in P.phases:
        path = os.path.join(P.locale_dir, fname)
        done, first, last = 0, None, None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                for line in f:
                    if not line.strip():
                        continue
                    i = json.loads(line)["idx"]
                    if first is None:
                        first = i
                    if i != (last + 1 if last is not None else lo) or i > hi:
                        sys.exit("%s: idx %d tidak berurutan dari %d atau di luar %d–%d "
                                 "(jalankan tools/qa_check.py --locale)" % (fname, i, lo, lo, hi))
                    last, done = i, done + 1
        rows.append((label, lo, hi, hi - lo + 1, done))
    return rows


def freq_coverage(P, src_to_translated):
    """Coverage berbobot kolom freq unique_strings.jsonl (profil coverage="freq")."""
    total = hit = 0
    with open(P.unique, encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            d = json.loads(line)
            total += d["freq"]
            if d["v"] in src_to_translated:
                hit += d["freq"]
    return hit, total


def dump_coverage(dump, src_to_translated, P=profiles.GLOBAL):
    path = P.path(dump)
    if not os.path.exists(path):
        return None
    total = hit = 0
    with open(path, encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            d = json.loads(line)
            if d.get("deleted"):
                continue
            total += 1
            hit += d["v"] in src_to_translated
    return hit, total


def build_block(P=profiles.GLOBAL):
    rows = phase_rows(P)
    src_to_translated, _ = load_translated_map(P.name)

    orig = [r for r in rows if not r[0].startswith("Update")]
    upd = [r for r in rows if r[0].startswith("Update")]
    all_total, all_done = sum(r[3] for r in rows), sum(r[4] for r in rows)
    o_total, o_done = sum(r[3] for r in orig), sum(r[4] for r in orig)
    u_total, u_done = sum(r[3] for r in upd), sum(r[4] for r in upd)

    out = [START, "",
           "## Overall progress", "",
           "| Measure | Done | Total | % |",
           "| --- | ---: | ---: | ---: |",
           "| **Unique strings translated (all)** | **%s** | **%s** | **%s** |"
           % (num(all_done), num(all_total), pct(all_done, all_total)),
           "| ↳ %s | %s | %s | %s |"
           % (P.corpus_label, num(o_done), num(o_total), pct(o_done, o_total))]
    if upd:
        out.append("| ↳ game-update strings (Update-N) | %s | %s | %s |"
                   % (num(u_done), num(u_total), pct(u_done, u_total)))
    if P.coverage == "freq":
        cov = freq_coverage(P, src_to_translated)
        out.append("| **In-game text coverage** — CN-only `%s` entries (`freq` in "
                   "`unique_strings.jsonl`; keys shared with global come via the bridge)"
                   " | **%s** | **%s** | **%s** |"
                   % (P.dumps[0][0], num(cov[0]), num(cov[1]), pct(*cov)))
    for name, dump in (P.dumps if P.coverage == "dump" else []):
        if not os.path.exists(P.path(dump)):
            sys.exit("%s tidak ada — jalankan dulu: python wwm_locmap.py dump %s %s"
                     % (dump, name, dump))
        cov = dump_coverage(dump, src_to_translated, P)
        if cov:
            out.append("| **In-game text coverage** — `%s` entries (`%s`) | **%s** | **%s** | **%s** |"
                       % (name, dump, num(cov[0]), num(cov[1]), pct(*cov)))
    out += ["",
            "Unique strings = rows of `unique_strings.jsonl` with a translation in "
            "`%s/`. In-game coverage counts every entry of the dumped file whose "
            "text has a translation — higher than the unique share because the "
            "earliest phases hold the most frequent strings." % P.rel(P.locale_dir),
            "",
            "## Phase status", "",
            "| Phase | Range | Status | Next idx | Done / total | % |",
            "| --- | --- | --- | --- | ---: | ---: |"]
    for label, lo, hi, total, done in rows:
        status = "done" if done == total else ("**active**" if done else "not started")
        nxt = "—" if done == total else num(lo + done)
        out.append("| %s | %s–%s | %s | %s | %s / %s | %s |"
                   % (label, num(lo), num(hi), status, nxt, num(done), num(total),
                      pct(done, total)))
    out += ["", END]
    return "\n".join(out), src_to_translated


def read_status(P=profiles.GLOBAL):
    """Kembalikan (isi dokumen, posisi START, posisi END)."""
    with open(P.status, encoding="utf-8", newline="") as f:
        doc = f.read()
    s, e = doc.find(START), doc.find(END)
    if s < 0 or e < s:
        sys.exit("penanda progress tidak ditemukan di %s" % P.status)
    return doc, s, e


def is_stale(profile="global"):
    """True kalau blok di Current-Status.md profil ini tidak sesuai data saat ini."""
    P = profiles.get(profile)
    block, _ = build_block(P)
    doc, s, e = read_status(P)
    return doc[s:e + len(END)].replace("\r\n", "\n") != block


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true", help="perbarui blok di Current-Status.md")
    g.add_argument("--check", action="store_true", help="exit 1 kalau blok basi")
    profiles.add_argument(ap)
    a = ap.parse_args()
    P = profiles.get(a.profile)
    if hasattr(sys.stdout, "reconfigure"):          # konsol Windows (cp1252) vs "↳"
        sys.stdout.reconfigure(encoding="utf-8")

    block, src_to_translated = build_block(P)
    doc, s, e = read_status(P)
    nl = "\r\n" if "\r\n" in doc else "\n"
    current = doc[s:e + len(END)].replace("\r\n", "\n")

    flag = "" if P.name == "global" else " --profile " + P.name
    if a.check:
        if current != block:
            print("%s: blok progress basi — jalankan "
                  "`python tools/progress.py%s --write` dan commit hasilnya." % (P.rel(P.status), flag))
            return 1
        print("%s: blok progress sesuai data." % P.rel(P.status))
        return 0

    if a.write:
        with open(P.status, "w", encoding="utf-8", newline="") as f:
            f.write(doc[:s] + block.replace("\n", nl) + doc[e + len(END):])
        print("ditulis:", P.status)
    else:
        print(block)
    return 0


if __name__ == "__main__":
    sys.exit(main())
